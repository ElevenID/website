import fs from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { generatedTextMatches } from './generated-text.mjs';

const defaultUiRoot = fileURLToPath(new URL('../', import.meta.url));
const isObject = (value) => value !== null && typeof value === 'object' && !Array.isArray(value);
const fail = (message) => { throw new Error(message); };

// Inputs and generated targets stay within this checkout, including every
// existing ancestor. A generated output must never follow a symlink.
function checkoutPath(root, relative, { optional = false } = {}) {
  const target = path.resolve(root, relative);
  if (!target.startsWith(`${root}${path.sep}`)) fail('Demo path escapes the checkout');
  let current = root;
  for (const part of path.relative(root, target).split(path.sep)) {
    current = path.join(current, part);
    try {
      if (fs.lstatSync(current).isSymbolicLink()) fail('Demo paths must not contain symlinks');
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
      if (!optional) throw error;
    }
  }
  return target;
}

function jsonFile(filename) {
  if (!fs.lstatSync(filename).isFile()) fail('Demo input must be a regular file');
  const value = JSON.parse(fs.readFileSync(filename, 'utf8'));
  if (!isObject(value)) fail('Demo input must be a JSON object');
  return value;
}

function validateWalletSchema(schema) {
  if (!isObject(schema) || schema.type !== 'object' || schema.additionalProperties !== false
      || !isObject(schema.properties) || !Array.isArray(schema.required) || schema.required.length === 0
      || !schema.required.every((name) => typeof name === 'string' && Object.hasOwn(schema.properties, name))
      || !isObject(schema.$defs?.stringList) || schema.$defs.stringList.type !== 'array'
      || schema.$defs.stringList.items?.type !== 'string') {
    fail('Demo wallet schema projection is invalid');
  }
}

export function generateDemoManifestModule({ uiRoot = defaultUiRoot, check = false } = {}) {
  const requestedRoot = path.resolve(uiRoot, '..');
  const root = fs.realpathSync(requestedRoot);
  if (root !== requestedRoot) fail('Demo checkout root must not contain symlinks');
  const uiRelative = path.relative(root, path.resolve(uiRoot));
  const source = checkoutPath(root, 'deploy-config/schemas/stack-demo-manifest.schema.json', { optional: true });
  const schemaOutput = checkoutPath(root, `${uiRelative}/src/generated/demoWalletSchema.generated.json`, { optional: true });
  const moduleOutput = checkoutPath(root, `${uiRelative}/src/generated/demoManifests.generated.js`, { optional: true });
  for (const filename of [schemaOutput, moduleOutput]) {
    if (fs.existsSync(filename) && !fs.lstatSync(filename).isFile()) fail('Generated demo target must be a regular file');
  }
  let walletSchema;
  const hasSource = fs.existsSync(source);
  if (hasSource) {
    const schema = jsonFile(source);
    const items = schema.$defs?.scenario?.properties?.wallets?.items;
    if (!isObject(items) || !isObject(schema.$defs?.stringList)) fail('Demo wallet schema source is invalid');
    walletSchema = { ...items, $defs: { stringList: schema.$defs.stringList } };
  } else {
    walletSchema = jsonFile(schemaOutput);
  }
  validateWalletSchema(walletSchema);

  const manifestRelative = `${uiRelative}/public/demos/manifests`;
  const index = jsonFile(checkoutPath(root, `${manifestRelative}/index.json`));
  if (!Array.isArray(index.releases) || index.releases.length === 0) fail('Demo index must contain releases');
  const manifests = {};
  const versions = new Set();
  for (const release of index.releases) {
    if (!isObject(release) || typeof release.stack_version !== 'string'
        || release.stack_version !== release.stack_version.trim()
        || !/^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$/.test(release.stack_version)
        || typeof release.mip_version !== 'string' || release.mip_version.trim() === '') {
      fail('Demo index contains an invalid release identity');
    }
    const version = release.stack_version;
    if (versions.has(version)) fail(`Duplicate demo stack version: ${version}`);
    versions.add(version);
    const manifest = jsonFile(checkoutPath(root, `${manifestRelative}/${version}.json`));
    if (manifest.stack_version !== version || manifest.mip_version !== release.mip_version) {
      fail(`Demo manifest index mismatch for ${version}`);
    }
    Object.defineProperty(manifests, version, { value: manifest, enumerable: true });
  }
  for (const field of ['latest_approved_stack_version', 'latest_available_stack_version']) {
    if (index[field] !== undefined && index[field] !== null && !versions.has(index[field])) {
      fail(`Demo index ${field} does not name a listed release`);
    }
  }

  const outputs = [[moduleOutput,
    `// Generated by scripts/generate-demo-manifest-module.mjs. Do not edit.\nexport const DEMO_INDEX = JSON.parse(${JSON.stringify(JSON.stringify(index))});\nexport const DEMO_MANIFESTS = JSON.parse(${JSON.stringify(JSON.stringify(manifests))});\n`]];
  if (hasSource) outputs.unshift([schemaOutput, `${JSON.stringify(walletSchema, null, 2)}\n`]);
  if (check) {
    for (const [filename, generated] of outputs) {
      if (!fs.existsSync(filename) || !fs.lstatSync(filename).isFile()
          || !generatedTextMatches(fs.readFileSync(filename, 'utf8'), generated)) {
        fail(`Generated demo artifact is stale: ${path.basename(filename)}. Run the generator and commit its output.`);
      }
    }
    return;
  }

  // Validate every input before creating output. Rename each completed file;
  // failures clean only this invocation's temporary files.
  const pending = [];
  try {
    for (const [filename, generated] of outputs) {
      fs.mkdirSync(path.dirname(filename), { recursive: true });
      const temporary = `${filename}.${randomUUID()}.tmp`;
      pending.push([temporary, filename]);
      fs.writeFileSync(temporary, generated, { encoding: 'utf8', flag: 'wx' });
    }
    for (const [temporary, filename] of pending) fs.renameSync(temporary, filename);
  } finally {
    for (const [temporary] of pending) fs.rmSync(temporary, { force: true });
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.slice(2).some((argument) => argument !== '--check') || process.argv.length > 3) {
    throw new Error('Usage: generate-demo-manifest-module.mjs [--check]');
  }
  generateDemoManifestModule({ check: process.argv.includes('--check') });
}
